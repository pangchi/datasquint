def _slug(s, n=40):
    return re.sub(r"[^a-z0-9]+", "_", (s or "").lower()).strip("_")[:n] or "query"


def _py_str(sql):
    """A readable Python literal for SQL: raw triple-quoted when safe, repr() otherwise."""
    if "'''" not in sql and not sql.endswith("\\") and "\r" not in sql:
        return "r'''" + sql + "'''"
    return repr(sql)


def _doc(s):
    """Text that is safe inside the script's docstring."""
    return str(s).replace(chr(92), "/").replace(chr(34) * 3, chr(39) * 3).replace(chr(13), " ")


def _env_prefix(name):
    return "DS_" + re.sub(r"[^A-Z0-9]+", "_", name.upper()).strip("_") + "_"


