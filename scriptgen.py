import argparse
import csv
import datetime
import os
import re
import sys
import tempfile

FILE_TABLES = __FILE_TABLES__

DATABASES = __DATABASES__

QUERIES = __QUERIES__

CSV_OPTS = "normalize_names=true, sample_size=-1, null_padding=true"


# ------------------------------------------------------------------ files -> DuckDB tables
EXCEL_ERRORS = {"#N/A", "#DIV/0!", "#VALUE!", "#REF!", "#NAME?", "#NUM!", "#NULL!", "#SPILL!", "#CALC!", "#GETTING_DATA"}


def xcell(v):
    """An Excel value as CSV text, the way Datasquint converts it (so column types match)."""
    # Both Excel readers (python-calamine and openpyxl) give the same CSV text: error cells are empty
    # (calamine already does that), and a date-time at exactly midnight is a date (calamine returns dates).
    if v is None or (isinstance(v, str) and v in EXCEL_ERRORS):
        return ""
    if isinstance(v, datetime.datetime):
        if not (v.hour or v.minute or v.second or v.microsecond):
            return v.date().isoformat()
        return v.isoformat(sep=" ")
    if isinstance(v, (datetime.date, datetime.time)):
        return v.isoformat()
    if isinstance(v, datetime.timedelta):
        return str(v)
    if isinstance(v, float) and v.is_integer() and abs(v) < 2 ** 53:
        return int(v)
    return v


def blank(cells):
    return not any(v is not None and str(v).strip() != "" for v in cells)


def sheet_rows(path, sheet):
    """(Excel row number, values) for every row of a sheet."""
    from openpyxl import load_workbook
    wb = load_workbook(path, read_only=True, data_only=True)
    try:
        if sheet not in wb.sheetnames:
            sys.exit(f"Sheet '{sheet}' not found in {path}. Sheets: {', '.join(wb.sheetnames)}")
        for r, row in enumerate(wb[sheet].iter_rows(values_only=True), start=1):
            yield r, list(row)
    finally:
        wb.close()


def csv_records(path, encoding, delim):
    with open(path, encoding=encoding or "utf-8-sig", newline="") as fh:
        yield from enumerate(csv.reader(fh, delimiter=delim or ","))


def write_csv(path, rows):
    with open(path, "w", encoding="utf-8", newline="") as fh:
        csv.writer(fh).writerows(rows)


def block_rows(load, path):
    """Rows of one table found inside a sheet/CSV holding several tables."""
    for a, b, lo, hi, skip in load["parts"]:
        skip = set(skip)
        width = hi - lo + 1
        if load["kind"] == "sheet":
            src = ((r, row[lo - 1:hi]) for r, row in sheet_rows(path, load["sheet"]) if a <= r <= b)
        else:
            src = ((i, row[lo:hi + 1]) for i, row in csv_records(path, load.get("encoding"), load.get("delim")) if a <= i <= b)
        for i, cells in src:
            if i in skip or blank(cells):
                continue
            yield ([xcell(v) for v in cells] + [""] * width)[:width]


def read_csv(con, name, path, opts):
    con.execute(f"CREATE TABLE {name} AS SELECT * FROM read_csv(?, {', '.join(x for x in (CSV_OPTS, opts) if x)})", [path])


def load_table(con, t, folder, tmp):
    path = os.path.join(folder, t["file"])
    if not os.path.exists(path):
        sys.exit(f"Missing data file: {path}\nPut the original '{t['file']}' there, or pass --data FOLDER.")
    load, name = t["load"], '"' + t["name"].replace('"', '""') + '"'
    opts = load.get("opts")   # the read_csv settings Datasquint used for this table
    if load.get("parts"):
        out = os.path.join(tmp, t["name"] + ".csv")
        write_csv(out, block_rows(load, path))
        read_csv(con, name, out, opts if opts is not None else "delim=','" + (", header=true" if load.get("header") else ""))
    elif load["kind"] == "sheet":
        off, width = load.get("col_offset", 0), load.get("width")
        out = os.path.join(tmp, t["name"] + ".csv")
        write_csv(out, ([xcell(v) for v in (row[off:off + width] if width else row[off:])]
                        for _, row in sheet_rows(path, load["sheet"]) if not blank(row)))
        read_csv(con, name, out, opts or "")
    else:
        src = path
        enc = load.get("encoding") or "utf-8-sig"
        if not enc.startswith("utf-8"):   # e.g. saved by Excel as Windows-1252: convert, as Datasquint did
            src = os.path.join(tmp, t["name"] + "_utf8.csv")
            with open(path, encoding=enc, newline="") as fi, open(src, "w", encoding="utf-8", newline="") as fo:
                fo.write(fi.read())
        read_csv(con, name, src, opts if opts is not None else ("delim='\\t'" if load.get("delim") == "\t" else ""))
    n = con.execute(f"SELECT count(*) FROM {name}").fetchone()[0]
    print(f"  loaded {t['name']}: {n:,} rows from {t['file']}" + (f" (sheet {t['sheet']})" if t.get("sheet") else ""))


def files_connection(folder, needed):
    try:
        import duckdb
    except ImportError:
        sys.exit("This script needs DuckDB for the attached files: pip install duckdb")
    con = duckdb.connect()
    tmp = tempfile.mkdtemp(prefix="datasquint_")
    for t in FILE_TABLES:
        if t["name"] in needed:
            load_table(con, t, folder, tmp)
    return con


# ------------------------------------------------------------------ databases
def db_connection(name):
    try:
        import psycopg
    except ImportError:
        sys.exit('This script needs psycopg for PostgreSQL: pip install "psycopg[binary]"')
    d = DATABASES[name]
    p = "DS_" + re.sub(r"[^A-Z0-9]+", "_", name.upper()).strip("_") + "_"
    pg = {"HOST": "PGHOST", "PORT": "PGPORT", "DBNAME": "PGDATABASE", "USER": "PGUSER"}
    env = lambda key, default: os.getenv(p + key) or os.getenv(pg[key]) or default
    password = os.getenv(p + "PASSWORD") or os.getenv("PGPASSWORD")
    if password is None:
        import getpass
        password = getpass.getpass(f"Password for {d.get('user')}@{d.get('host')} ({name}): ")
    conn = psycopg.connect(host=env("HOST", d.get("host")), port=env("PORT", d.get("port")),
                           dbname=env("DBNAME", d.get("dbname")), user=env("USER", d.get("user")),
                           password=password, sslmode=d.get("sslmode") or "prefer", connect_timeout=15)
    conn.read_only = True   # this script only reads
    return conn


# ------------------------------------------------------------------ run
def show(columns, rows, limit):
    if not columns or limit <= 0:
        return
    rows = [["" if v is None else str(v) for v in r] for r in rows[:limit]]
    widths = [min(30, max([len(c)] + [len(r[i]) for r in rows])) for i, c in enumerate(columns)]
    line = lambda cells: "  " + " | ".join(str(c)[:w].ljust(w) for c, w in zip(cells, widths))
    print(line(columns))
    print("  " + "-+-".join("-" * w for w in widths))
    for r in rows:
        print(line(r))


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
